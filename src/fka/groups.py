"""Permutation groups, without SageMath.

The thesis names every node's automorphism group -- ``C2``, ``D4``, ``S4``,
``C2 x S4``, ``PSL(3,2)``, ``(((C2 x C2 x C2 x C2) : C2) : C2) : C2``
(Figures 5.1-5.4). The legacy notebooks got those from GAP via SageMath, which
is not on every machine this runs on. This is the pure-Python fallback; where
Sage is present :mod:`fka.backends.sage_backend` defers to GAP's
``StructureDescription``, which is authoritative.

Naming is by *invariant fingerprint*, not a proof of isomorphism. A group is
matched against a catalogue of cyclic, dihedral, symmetric, alternating and
quaternion groups and their direct products, on order, the multiset of element
orders, abelian-ness and centre order, derived subgroup order, and the multiset
of conjugacy class sizes. Two non-isomorphic groups agreeing on all five would
be misnamed -- it does not happen for anything in the thesis' figures, and the
catalogue is small enough to check, but the limitation is real. :func:`identify`
reports how it matched and returns an ``order N`` placeholder rather than a
guess when nothing fits.

Permutations are tuples of images on ``0 .. n-1``: ``p[i]`` is the image of ``i``.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from functools import lru_cache
from typing import Optional, Sequence

__all__ = [
    "Perm",
    "identity",
    "compose",
    "inverse",
    "perm_order",
    "cycle_notation",
    "closure",
    "PermutationGroup",
    "identify",
]

Perm = tuple[int, ...]

#: Upper bound on how many group elements will be enumerated. Every group in
#: the thesis is far below this; the cap turns a runaway case into a clear
#: error instead of an apparent hang.
MAX_GROUP_ORDER = 200_000


def identity(n: int) -> Perm:
    return tuple(range(n))


def compose(p: Perm, q: Perm) -> Perm:
    """``(p . q)(i) = p(q(i))``."""
    return tuple(p[q[i]] for i in range(len(q)))


def inverse(p: Perm) -> Perm:
    out = [0] * len(p)
    for i, x in enumerate(p):
        out[x] = i
    return tuple(out)


def perm_order(p: Perm) -> int:
    """Multiplicative order of ``p``."""
    n = len(p)
    seen = [False] * n
    from math import lcm

    order = 1
    for i in range(n):
        if seen[i]:
            continue
        length = 0
        j = i
        while not seen[j]:
            seen[j] = True
            j = p[j]
            length += 1
        order = lcm(order, length)
    return order


def cycle_notation(p: Perm, *, one_indexed: bool = True) -> str:
    """Render ``p`` in disjoint-cycle notation, e.g. ``(1,4)(5,6)``.

    Fixed points are omitted; the identity renders as ``()``.
    """
    shift = 1 if one_indexed else 0
    n = len(p)
    seen = [False] * n
    parts: list[str] = []
    for i in range(n):
        if seen[i] or p[i] == i:
            seen[i] = True
            continue
        cycle = []
        j = i
        while not seen[j]:
            seen[j] = True
            cycle.append(j + shift)
            j = p[j]
        if len(cycle) > 1:
            parts.append("(" + ",".join(map(str, cycle)) + ")")
    return "".join(parts) if parts else "()"


def closure(generators: Sequence[Perm], n: int, *, cap: int = MAX_GROUP_ORDER) -> list[Perm]:
    """All elements of the group generated by ``generators`` (breadth-first)."""
    e = identity(n)
    seen = {e}
    frontier = [e]
    gens = [g for g in generators if g != e]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = compose(g, x)
                if y not in seen:
                    seen.add(y)
                    if len(seen) > cap:
                        raise ValueError(
                            f"group exceeded {cap} elements; refusing to enumerate further"
                        )
                    nxt.append(y)
        frontier = nxt
    return sorted(seen)


@dataclass(slots=True)
class PermutationGroup:
    """A finite permutation group given by its full element list.

    Built from generators via :meth:`from_generators`. Holding every element is
    wasteful in general but is the simplest thing that supports the invariants
    below exactly, and the groups here are small by construction.
    """

    degree: int
    elements: list[Perm]
    generators: list[Perm] = field(default_factory=list)
    #: Memoised invariants. The full fingerprint costs O(|G|^2) compositions,
    #: and catalogue lookup compares many candidates against one query.
    _cheap: Optional[tuple] = None
    _fingerprint: Optional[tuple] = None

    @classmethod
    def from_generators(
        cls, generators: Sequence[Perm], n: int, *, cap: int = MAX_GROUP_ORDER
    ) -> "PermutationGroup":
        elements = closure(generators, n, cap=cap)
        return cls(degree=n, elements=elements, generators=list(generators))

    @property
    def order(self) -> int:
        return len(self.elements)

    def is_trivial(self) -> bool:
        return self.order == 1

    def element_order_profile(self) -> tuple[tuple[int, int], ...]:
        """Sorted ``(element order, count)`` pairs."""
        counts: dict[int, int] = {}
        for p in self.elements:
            o = perm_order(p)
            counts[o] = counts.get(o, 0) + 1
        return tuple(sorted(counts.items()))

    def is_abelian(self) -> bool:
        gens = self.generators or self.elements
        return all(compose(a, b) == compose(b, a) for a in gens for b in gens)

    def centre(self) -> list[Perm]:
        return [z for z in self.elements if all(
            compose(z, g) == compose(g, z) for g in self.elements
        )]

    def derived_subgroup(self) -> list[Perm]:
        """The commutator subgroup ``[G, G]``."""
        comms = set()
        for a in self.elements:
            ai = inverse(a)
            for b in self.elements:
                comms.add(compose(compose(a, b), compose(ai, inverse(b))))
        return closure(sorted(comms), self.degree)

    def conjugacy_class_sizes(self) -> tuple[int, ...]:
        remaining = set(self.elements)
        sizes: list[int] = []
        while remaining:
            x = next(iter(remaining))
            cls = {compose(compose(g, x), inverse(g)) for g in self.elements}
            sizes.append(len(cls))
            remaining -= cls
        return tuple(sorted(sizes))

    def orbits(self) -> list[tuple[int, ...]]:
        """Orbits of the group on ``0 .. degree-1``, ascending."""
        unseen = set(range(self.degree))
        out: list[tuple[int, ...]] = []
        while unseen:
            v = min(unseen)
            orb = sorted({p[v] for p in self.elements})
            out.append(tuple(orb))
            unseen -= set(orb)
        return out

    def minimal_generators(self) -> list[Perm]:
        """A small (greedy, not provably minimum) generating set.

        Elements are tried in descending order so high-order elements are
        picked first, which tends to give the short presentations the thesis
        quotes.
        """
        if self.order == 1:
            return []
        chosen: list[Perm] = []
        current = {identity(self.degree)}
        pool = sorted(self.elements, key=lambda p: -perm_order(p))
        for p in pool:
            if p in current:
                continue
            chosen.append(p)
            current = set(closure(chosen, self.degree))
            if len(current) == self.order:
                break
        return chosen

    def cheap_signature(self) -> tuple:
        """Invariants costing ``O(|G| * degree)``: order, element orders, abelian.

        Used to reject catalogue candidates before paying for the full
        fingerprint, which needs conjugacy classes and so costs ``O(|G|^2)``.
        """
        if self._cheap is None:
            self._cheap = (self.order, self.element_order_profile(), self.is_abelian())
        return self._cheap

    def fingerprint(self) -> tuple:
        """Invariants used to name the group. See the module docstring."""
        if self._fingerprint is None:
            self._fingerprint = self.cheap_signature() + (
                len(self.centre()),
                len(self.derived_subgroup()),
                self.conjugacy_class_sizes(),
            )
        return self._fingerprint


