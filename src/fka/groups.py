"""Permutation groups, without SageMath.

The thesis names every node's automorphism group -- ``C2``, ``D4``, ``S4``,
``C2 x S4``, ``PSL(3,2)``, ``(((C2 x C2 x C2 x C2) : C2) : C2) : C2``
(Figures 5.1-5.4). This is the pure-Python fallback for machines without
SageMath; where Sage is present :mod:`fka.backends.sage_backend` defers to GAP's
``StructureDescription``, which is authoritative.

Naming is by *invariant fingerprint*, not a proof of isomorphism. A group is
matched against candidates of the same order -- cyclic, dihedral, symmetric,
alternating, quaternion, and their direct and wreath products -- on order, the
multiset of element orders, abelian-ness, centre order, derived-subgroup order,
and the multiset of conjugacy class sizes. Two non-isomorphic groups agreeing on
all six would be misnamed; that does not happen for anything in the thesis'
figures, but the limitation is real. :func:`identify` reports how it matched and
returns an ``order N`` placeholder rather than a guess when nothing fits.

Candidates are derived from the order arithmetically -- ``D_m`` is a candidate
for ``2m``, ``S_k`` for ``k!`` -- so nothing is enumerated that the order
already rules out. The two infinite families are recognised *without* being
constructed: a cyclic group is an abelian group with an element of full order, a
dihedral one has the rotation and the reflection count. That matters, because
building ``D720`` to compare against a group of order 1440 costs more than the
answer is worth.

Permutations are tuples of images on ``0 .. n-1``: ``p[i]`` is the image of ``i``.
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass, field
from functools import lru_cache
from math import factorial, isqrt, lcm, prod
from typing import Callable, Iterator, Optional, Sequence

__all__ = [
    "Perm",
    "identity",
    "compose",
    "inverse",
    "conjugate",
    "commutator",
    "perm_order",
    "cycle_notation",
    "closure",
    "PermutationGroup",
    "identify",
]

Perm = tuple[int, ...]

#: Upper bound on how many group elements will be enumerated. Every group in
#: the thesis is far below this; the cap turns a runaway case into a clear
#: error instead of an apparent hang.
MAX_GROUP_ORDER = 200_000

#: Groups above this order are not matched against candidates: enumerating
#: their elements and conjugacy classes stops being cheap, and nothing in the
#: thesis needs it. Larger groups fall through to :data:`_SPECIAL` or come back
#: unidentified, which is a prompt to run the SageMath backend.
MAX_CATALOGUE_ORDER = 2_000

#: Atoms above this order are not *constructed* as product factors. Cost is
#: degree times order, so a large ``C_n`` or ``D_m`` is expensive to build and
#: almost never the answer -- and when it is, :func:`_named_cyclic` and
#: :func:`_named_dihedral` name it without building anything.
MAX_ATOM_ORDER = 256


def identity(n: int) -> Perm:
    return tuple(range(n))


def compose(p: Perm, q: Perm) -> Perm:
    """``(p . q)(i) = p(q(i))``."""
    return tuple(p[q[i]] for i in range(len(q)))


def inverse(p: Perm) -> Perm:
    out = [0] * len(p)
    for i, x in enumerate(p):
        out[x] = i
    return tuple(out)


def conjugate(g: Perm, x: Perm) -> Perm:
    """``g x g^-1``."""
    return compose(compose(g, x), inverse(g))


def commutator(a: Perm, b: Perm) -> Perm:
    """``[a, b] = a b a^-1 b^-1``."""
    return compose(compose(a, b), compose(inverse(a), inverse(b)))


def perm_order(p: Perm) -> int:
    """Multiplicative order of ``p``."""
    n = len(p)
    seen = [False] * n
    order = 1
    for i in range(n):
        if seen[i]:
            continue
        length = 0
        j = i
        while not seen[j]:
            seen[j] = True
            j = p[j]
            length += 1
        order = lcm(order, length)
    return order


def cycle_notation(p: Perm, *, one_indexed: bool = True) -> str:
    """Render ``p`` in disjoint-cycle notation, e.g. ``(1,4)(5,6)``.

    Fixed points are omitted; the identity renders as ``()``.
    """
    shift = 1 if one_indexed else 0
    n = len(p)
    seen = [False] * n
    parts: list[str] = []
    for i in range(n):
        if seen[i] or p[i] == i:
            seen[i] = True
            continue
        cycle = []
        j = i
        while not seen[j]:
            seen[j] = True
            cycle.append(j + shift)
            j = p[j]
        if len(cycle) > 1:
            parts.append("(" + ",".join(map(str, cycle)) + ")")
    return "".join(parts) if parts else "()"


def closure(
    generators: Sequence[Perm], n: int, *, cap: int = MAX_GROUP_ORDER
) -> list[Perm]:
    """All elements of the group generated by ``generators`` (breadth-first)."""
    e = identity(n)
    seen = {e}
    frontier = [e]
    gens = [g for g in generators if g != e]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = compose(g, x)
                if y not in seen:
                    seen.add(y)
                    if len(seen) > cap:
                        raise ValueError(
                            f"group exceeded {cap} elements; refusing to enumerate further"
                        )
                    nxt.append(y)
        frontier = nxt
    return sorted(seen)


@dataclass(slots=True)
class PermutationGroup:
    """A finite permutation group given by its full element list.

    Built from generators via :meth:`from_generators`. Holding every element is
    wasteful in general but is the simplest thing that supports the invariants
    below exactly, and the groups here are small by construction.

    The invariants take ``generators or elements``: a subgroup-defining property
    that holds on a generating set holds on the whole group, so the generators
    are enough wherever one is available, and the element list is the honest
    fallback when :class:`PermutationGroup` was built without them.
    """

    degree: int
    elements: list[Perm]
    generators: list[Perm] = field(default_factory=list)
    #: Memoised. The full fingerprint needs conjugacy classes, and a lookup
    #: compares many candidates against one query.
    _cheap: Optional[tuple] = None
    _fingerprint: Optional[tuple] = None

    @classmethod
    def from_generators(
        cls, generators: Sequence[Perm], n: int, *, cap: int = MAX_GROUP_ORDER
    ) -> "PermutationGroup":
        elements = closure(generators, n, cap=cap)
        return cls(degree=n, elements=elements, generators=list(generators))

    @property
    def order(self) -> int:
        return len(self.elements)

    def is_trivial(self) -> bool:
        return self.order == 1

    def _gens(self) -> list[Perm]:
        return self.generators or self.elements

    def element_order_profile(self) -> tuple[tuple[int, int], ...]:
        """Sorted ``(element order, count)`` pairs."""
        counts: dict[int, int] = {}
        for p in self.elements:
            o = perm_order(p)
            counts[o] = counts.get(o, 0) + 1
        return tuple(sorted(counts.items()))

    def is_abelian(self) -> bool:
        gens = self._gens()
        return all(compose(a, b) == compose(b, a) for a in gens for b in gens)

    def centre(self) -> list[Perm]:
        """``Z(G)``. Commuting with the generators is commuting with the group."""
        gens = self._gens()
        return [
            z for z in self.elements
            if all(compose(z, g) == compose(g, z) for g in gens)
        ]

    def derived_subgroup(self) -> list[Perm]:
        """``[G, G]``: the normal closure of the generators' commutators.

        Not merely the subgroup they generate -- that can be too small -- so the
        conjugates are folded back in until the set is stable.
        """
        gens = self._gens()
        K = set(closure([commutator(a, b) for a in gens for b in gens], self.degree))
        while True:
            extra = {conjugate(g, k) for g in gens for k in K} - K
            if not extra:
                return sorted(K)
            K = set(closure(sorted(K | extra), self.degree))

    def conjugacy_class_sizes(self) -> tuple[int, ...]:
        """Sorted class sizes. A class is an orbit under conjugation by generators."""
        remaining = set(self.elements)
        gens = self._gens()
        sizes: list[int] = []
        while remaining:
            x = next(iter(remaining))
            cls = {x}
            frontier = [x]
            while frontier:
                y = frontier.pop()
                for g in gens:
                    z = conjugate(g, y)
                    if z not in cls:
                        cls.add(z)
                        frontier.append(z)
            sizes.append(len(cls))
            remaining -= cls
        return tuple(sorted(sizes))

    def orbits(self) -> list[tuple[int, ...]]:
        """Orbits of the group on ``0 .. degree-1``, ascending."""
        unseen = set(range(self.degree))
        out: list[tuple[int, ...]] = []
        while unseen:
            v = min(unseen)
            orb = sorted({p[v] for p in self.elements})
            out.append(tuple(orb))
            unseen -= set(orb)
        return out

    def minimal_generators(self) -> list[Perm]:
        """A small (greedy, not provably minimum) generating set.

        Elements are tried in descending order so high-order elements are
        picked first, which tends to give the short presentations the thesis
        quotes.
        """
        if self.order == 1:
            return []
        chosen: list[Perm] = []
        current = {identity(self.degree)}
        for p in sorted(self.elements, key=lambda p: -perm_order(p)):
            if p in current:
                continue
            chosen.append(p)
            current = set(closure(chosen, self.degree))
            if len(current) == self.order:
                break
        return chosen

    def cheap_signature(self) -> tuple:
        """Order, element-order profile and abelian-ness.

        Rejects a candidate before paying for the full fingerprint.
        """
        if self._cheap is None:
            self._cheap = (self.order, self.element_order_profile(), self.is_abelian())
        return self._cheap

    def fingerprint(self) -> tuple:
        """The invariants a name is matched on. See the module docstring."""
        if self._fingerprint is None:
            self._fingerprint = self.cheap_signature() + (
                len(self.centre()),
                len(self.derived_subgroup()),
                self.conjugacy_class_sizes(),
            )
        return self._fingerprint


