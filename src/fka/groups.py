# named groups, constructed on demand
# ----------------------------------------------------------------------
def _cyclic(n: int) -> PermutationGroup:
    return PermutationGroup.from_generators([tuple((i + 1) % n for i in range(n))], n)


def _dihedral(m: int) -> PermutationGroup:
    """Symmetries of the ``m``-gon, order ``2m``.

    The thesis and SageMath's ``DihedralGroup`` both index by the polygon, so
    ``D4`` has order 8.
    """
    rot = tuple((i + 1) % m for i in range(m))
    ref = tuple((-i) % m for i in range(m))
    return PermutationGroup.from_generators([rot, ref], m)


def _symmetric(k: int) -> PermutationGroup:
    swap = list(range(k))
    swap[0], swap[1] = swap[1], swap[0]
    return PermutationGroup.from_generators(
        [tuple(range(1, k)) + (0,), tuple(swap)], k
    )


def _alternating(k: int) -> PermutationGroup:
    gens = []
    for i in range(k - 2):
        p = list(range(k))
        p[i], p[i + 1], p[i + 2] = p[i + 1], p[i + 2], p[i]
        gens.append(tuple(p))
    return PermutationGroup.from_generators(gens, k)


#: Unit quaternion multiplication on ``1, i, j, k``: ``(index, negated)``.
#: Everything else follows from ``i^2 = j^2 = k^2 = ijk = -1``.
_IJK = {(1, 2): (3, False), (2, 3): (1, False), (3, 1): (2, False)}


def _quaternion8() -> PermutationGroup:
    """Q8 as its own regular representation on the eight units ``+-1, +-i, +-j, +-k``."""

    def mul(a: tuple[int, bool], b: tuple[int, bool]) -> tuple[int, bool]:
        (ua, na), (ub, nb) = a, b
        neg = na ^ nb
        if ua == 0:
            return ub, neg
        if ub == 0:
            return ua, neg
        if ua == ub:
            return 0, not neg  # i^2 = j^2 = k^2 = -1
        if (ua, ub) in _IJK:
            u, flip = _IJK[(ua, ub)]
        else:
            u, flip = _IJK[(ub, ua)][0], True  # anti-commutative
        return u, neg ^ flip

    units = [(u, n) for u in range(4) for n in (False, True)]
    index = {e: i for i, e in enumerate(units)}
    gens = [
        tuple(index[mul(g, x)] for x in units)
        for g in ((1, False), (2, False))  # left multiplication by i and by j
    ]
    return PermutationGroup.from_generators(gens, 8)


#: ``(name, order, builder)``. Built on demand: the fingerprint needs conjugacy
#: classes, so constructing a candidate that the order already rules out is pure
#: waste.
_Atom = tuple[str, int, Callable[[], PermutationGroup]]


def _atoms_dividing(order: int) -> Iterator[_Atom]:
    """Every named atomic group whose order divides ``order``.

    Type-major -- cyclic, dihedral, symmetric, alternating, quaternion -- so a
    group is named ``S4`` rather than as some product isomorphic to it.
    """
    for d in range(2, min(order, MAX_ATOM_ORDER) + 1):
        if order % d == 0:
            yield f"C{d}", d, lambda d=d: _cyclic(d)
    for m in range(3, min(order // 2, MAX_ATOM_ORDER // 2) + 1):
        if order % (2 * m) == 0:
            yield f"D{m}", 2 * m, lambda m=m: _dihedral(m)
    for k in itertools.count(3):
        f = factorial(k)
        if f > order:
            break
        if order % f == 0:
            yield f"S{k}", f, lambda k=k: _symmetric(k)
    for k in itertools.count(4):
        h = factorial(k) // 2
        if h > order:
            break
        if order % h == 0:
            yield f"A{k}", h, lambda k=k: _alternating(k)
    if order % 8 == 0:
        yield "Q8", 8, _quaternion8


def _product(a: PermutationGroup, b: PermutationGroup) -> PermutationGroup:
    """Direct product, acting on the disjoint union of the two point sets."""
    na, nb = a.degree, b.degree
    gens = [tuple(g) + tuple(na + i for i in range(nb)) for g in a._gens()]
    gens += [tuple(range(na)) + tuple(na + g[i] for i in range(nb)) for g in b._gens()]
    return PermutationGroup.from_generators(gens, na + nb)


def _wreath(a: PermutationGroup, b: PermutationGroup) -> PermutationGroup:
    """``A wr B``, acting imprimitively, of order ``|A|^m * |B|`` for ``m = deg B``.

    ``B`` permutes ``m`` blocks, each a copy of ``A``'s domain, and ``A`` acts
    inside one block. These are needed, not decoration: the thesis names the
    root of the f2/g2 tree ``D4 wr S2``, and Cameron's proposition (Section 4.4)
    says cograph automorphism groups are built from direct and wreath products
    with symmetric groups. Direct products alone could never name them.
    """
    p, m = a.degree, b.degree
    n = p * m
    gens: list[Perm] = []
    for g in a._gens():
        gens.append(tuple(g) + tuple(range(p, n)))
    for h in b._gens():
        img = [0] * n
        for blk in range(m):
            for i in range(p):
                img[blk * p + i] = h[blk] * p + i
        gens.append(tuple(img))
    return PermutationGroup.from_generators(gens, n)


def _exact_root(value: int, m: int) -> Optional[int]:
    """The integer ``r`` with ``r**m == value``, or ``None``."""
    r = isqrt(value) if m == 2 else round(value ** (1.0 / m))
    for cand in (r - 1, r, r + 1):
        if cand > 0 and cand**m == value:
            return cand
    return None


#: Top groups for wreath products, small enough that ``|A|^deg B`` stays modest.
_WREATH_TOPS: tuple[tuple[str, Callable[[], PermutationGroup]], ...] = (
    ("C2", lambda: _cyclic(2)),
    ("C3", lambda: _cyclic(3)),
    ("C4", lambda: _cyclic(4)),
    ("S3", lambda: _symmetric(3)),
    ("S4", lambda: _symmetric(4)),
)


@lru_cache(maxsize=256)
def _candidates(order: int) -> tuple[tuple[str, PermutationGroup], ...]:
    """Named groups of exactly ``order``, cheapest spelling first.

    Atoms, then direct products of two and of three atoms, then wreath products.
    Earlier entries win ties.
    """
    atoms = list(_atoms_dividing(order))
    built: dict[str, PermutationGroup] = {}

    def get(spec: _Atom) -> PermutationGroup:
        name, _, build = spec
        if name not in built:
            built[name] = build()
        return built[name]

    out: list[tuple[str, PermutationGroup]] = []
    for spec in atoms:
        if spec[1] == order:
            out.append((_spell(spec[0]), get(spec)))

    for k in (2, 3):
        for combo in itertools.combinations_with_replacement(atoms, k):
            if prod(o for _, o, _ in combo) != order:
                continue
            group = get(combo[0])
            for spec in combo[1:]:
                group = _product(group, get(spec))
            out.append((" x ".join(_spell(n) for n, _, _ in combo), group))

    for top_name, top in _WREATH_TOPS:
        b = top()
        if order % b.order:
            continue
        root = _exact_root(order // b.order, b.degree)
        if root is None:
            continue
        for spec in atoms:
            if spec[1] == root:
                out.append((f"{_spell(spec[0])} wr {top_name}", _wreath(get(spec), b)))

    return tuple(out)


#: Simple groups no product spells, keyed by
#: ``(order, abelian, |centre|, |derived subgroup|)``. A non-abelian group equal
#: to its own derived subgroup with trivial centre is perfect and centreless,
#: which pins this down at this order. PSL(3,2) is the Fano plane's automorphism
#: group (thesis Figure 5.2).
_SPECIAL: dict[tuple[int, bool, int, int], str] = {
    (168, False, 1, 168): "PSL(3,2)",
}

#: Where the catalogue's spelling differs from the thesis'. Applied per *factor*,
#: so ``D3`` reads as ``S3`` standalone and in ``S3 x D4`` alike -- naming the
#: same group two ways in one artifact is the defect this avoids.
_ALIASES: dict[str, str] = {"D3": "S3"}


def _spell(name: str) -> str:
    return _ALIASES.get(name, name)


def _named_cyclic(group: "PermutationGroup") -> Optional[str]:
    """``C{n}`` when ``group`` is cyclic: abelian with an element of full order."""
    if not group.is_abelian():
        return None
    n = group.order
    if any(perm_order(p) == n for p in group.elements):
        return f"C{n}"
    return None


def _named_dihedral(group: "PermutationGroup") -> Optional[str]:
    """``D{m}`` when ``group`` looks dihedral of order ``2m``.

    ``D_m`` is ``m`` rotations and ``m`` reflections: an element of order ``m``,
    and involutions numbering ``m``, or ``m + 1`` when ``m`` is even because the
    half-turn is one too. Same standing as everything else here -- an invariant
    match, not an isomorphism proof.
    """
    n = group.order
    if n % 2 or n < 6 or group.is_abelian():
        return None
    m = n // 2
    if not any(perm_order(p) == m for p in group.elements):
        return None
    involutions = sum(1 for p in group.elements if perm_order(p) == 2)
    return f"D{m}" if involutions == (m + 1 if m % 2 == 0 else m) else None


@dataclass(frozen=True, slots=True)
class GroupIdentification:
    """The result of naming a group."""

    name: str
    order: int
    abelian: bool
    method: str  # "trivial" | "catalogue" | "special" | "unidentified"

    def __str__(self) -> str:
        return self.name


def identify(group: PermutationGroup) -> GroupIdentification:
    """Name ``group`` by invariant fingerprint. See the module docstring.

    Returns an ``order N`` placeholder when nothing matches, rather than
    guessing -- an unnamed group is a prompt to run the SageMath backend, not a
    result to quote.
    """
    order = group.order
    if order == 1:
        return GroupIdentification("C1", 1, True, "trivial")

    abelian = group.is_abelian()

    for name in (_named_cyclic(group), _named_dihedral(group)):
        if name is not None:
            return GroupIdentification(_spell(name), order, abelian, "catalogue")

    if order <= MAX_CATALOGUE_ORDER:
        cheap = group.cheap_signature()
        matches = [
            (name, c) for name, c in _candidates(order) if c.cheap_signature() == cheap
        ]
        if matches:
            fp = group.fingerprint()
            for name, candidate in matches:
                if candidate.fingerprint() == fp:
                    return GroupIdentification(name, order, abelian, "catalogue")

        key = (order, abelian, len(group.centre()), len(group.derived_subgroup()))
        if key in _SPECIAL:
            return GroupIdentification(_SPECIAL[key], order, abelian, "special")

    return GroupIdentification(
        f"order {order} ({'abelian' if abelian else 'non-abelian'}, unidentified)",
        order,
        abelian,
        "unidentified",
    )
